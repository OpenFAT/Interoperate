#!/usr/bin/env bash
# Generate golden netlists by *running* a pinned xschem (clean-room, D1) on every
# bench in benches.txt. Inputs come from fetch.sh (run it first).
#
#   corpus/golden.sh [name-regex]
#
# Outputs, all under corpus/.cache/golden/:
#   <name>.spice      SPICE netlist (xschem -s, default options)
#   <name>.cdl        LVS netlist   (same, with Tcl `lvs_netlist=1`: lvs_format, top as .subckt)
#   <name>.<mode>.log xschem stdout+stderr
#   REPORT.txt        one line per (bench, mode) of this run: ok | FAIL <reason>
# Exit status: 0 when every bench produced both netlists, 1 otherwise.
#
# XSCHEM=/path/to/xschem overrides the pinned nix build (useful off-Linux).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cache="$here/.cache"
src="$cache/src"
out="$cache/golden"
filter="${1:-}"

# nixpkgs revision that builds xschem 3.4.7 (matches the xschem tag in fetch.sh).
nixpkgs_rev=331800de5053fcebacf6813adb5db9c9dca22a0c
if [[ -z "${XSCHEM:-}" ]]; then
  XSCHEM="$(nix build --no-link --print-out-paths "github:NixOS/nixpkgs/$nixpkgs_rev#xschem")/bin/xschem"
  # PDK generator symbols (sky130 test_generators) exec `tclsh`.
  PATH="$(nix build --no-link --print-out-paths "github:NixOS/nixpkgs/$nixpkgs_rev#tcl^out")/bin:$PATH"
fi
[[ -x "$XSCHEM" ]] || { echo "xschem not found: $XSCHEM" >&2; exit 2; }
[[ -d "$src/xschem" ]] || { echo "run corpus/fetch.sh first" >&2; exit 2; }

# A filtered run regenerates only the matching benches and keeps the rest.
[[ -z "$filter" ]] && rm -rf "${out:?}"
rm -rf "${cache:?}/rc" "${cache:?}/home" "${cache:?}/pdk"
mkdir -p "$out" "$cache/rc" "$cache/home"

# --- rcfiles: one per library set. PDK benches source the PDK's own xschemrc,
# exactly as a user would, with PDK_ROOT/PDK pointing into the cache.
# The xschem set mirrors xschem's compiled-in default library path, re-rooted
# at the fetched (same-tag) xschem_library.
xs_lib="$src/xschem/xschem_library"
{
  echo 'set XSCHEM_LIBRARY_PATH {}'
  for d in devices examples ngspice ngspice_verilog_cosim logic xschem_simulator \
           generators inst_sch_select binto7seg pcb rom8k; do
    echo "append XSCHEM_LIBRARY_PATH :$xs_lib/$d"
  done
} >"$cache/rc/xschem.rc"
# sky130/gf180 rcs open a TCP listener (bespice); goldens must not need a free port.
no_tcp='unset -nocomplain bespice_listen_port'

# sky130: open_pdks layout ($PDK_ROOT/sky130A/libs.tech/xschem); models are not
# fetched (they are generated by open_pdks), so SKYWATER_MODELS paths are text only.
mkdir -p "$cache/pdk/sky130A/libs.tech"
ln -s "$src/xschem_sky130" "$cache/pdk/sky130A/libs.tech/xschem"
cat >"$cache/rc/sky130.rc" <<EOF
set env(PDK_ROOT) $cache/pdk
set env(PDK) sky130A
source $cache/pdk/sky130A/libs.tech/xschem/xschemrc
$no_tcp
EOF

# gf180: the repo root is what the PDK xschemrc expects as PDK_ROOT (models/ngspice).
cat >"$cache/rc/gf180.rc" <<EOF
set env(PDK_ROOT) $src/gf180mcu_fd_pr
source $src/gf180mcu_fd_pr/cells/xschem/xschemrc
append XSCHEM_LIBRARY_PATH :$src/gf180mcu_fd_pr/cells/xschem
$no_tcp
EOF

cat >"$cache/rc/ihp.rc" <<EOF
set env(PDK_ROOT) $src/ihp_open_pdk
set env(PDK) ihp-sg13g2
source $src/ihp_open_pdk/ihp-sg13g2/libs.tech/xschem/xschemrc
EOF

# `xschem -q -n` exits 10 whenever ERC finds anything (e.g. "undriven node"),
# and prints nothing. Netlisting from --script instead lets us keep the ERC
# text in the log; the netlist bytes are identical to `-q -n` (checked).
cat >"$cache/rc/netlist.tcl" <<'EOF'
xschem netlist
puts "ERC-BEGIN"
puts [xschem get infowindow_text]
puts "ERC-END"
exit 0
EOF
# Lines outside the ERC block matching this mean broken inputs (missing symbols etc.).
error_re='not found|cannot|can.t open|unable|invalid command|no such|error'

report="$out/REPORT.txt"
: >"$report"
work="$cache/work"

run_mode() { # name pdk file mode
  local name="$1" pdk="$2" file="$3" mode="$4" ext tcl=() cell log reason=""
  cell="$(basename "$file" .sch)"
  # lvs_netlist is xschem's documented Tcl option (Simulation > LVS menu).
  if [[ "$mode" == lvs ]]; then ext=cdl; tcl=(--tcl 'set lvs_netlist 1'); else ext=spice; fi
  log="$out/$name.$ext.log"
  rm -rf "$work" && mkdir -p "$work"
  local status=0
  (cd "$work" && HOME="$cache/home" timeout 120 "$XSCHEM" -x -r -s -o "$work" \
      --rcfile "$cache/rc/$pdk.rc" "${tcl[@]}" --script "$cache/rc/netlist.tcl" "$file" \
      </dev/null) >"$log" 2>&1 || status=$?
  local problems
  problems="$(sed '/^ERC-BEGIN$/,/^ERC-END$/d' "$log" | grep -iE "$error_re" || true)"
  if [[ $status -ne 0 ]]; then
    reason="xschem exit $status"
  elif [[ ! -s "$work/$cell.spice" ]]; then
    reason="no netlist written"
  elif [[ -n "$problems" ]]; then
    reason="$(head -1 <<<"$problems" | tr -s ' \t' ' ' | cut -c1-160)"
  fi
  if [[ -s "$work/$cell.spice" ]]; then mv "$work/$cell.spice" "$out/$name.$ext"; fi
  if [[ -n "$reason" ]]; then
    printf '%-44s %-5s FAIL %s\n' "$name" "$mode" "$reason" >>"$report"
  else
    printf '%-44s %-5s ok\n' "$name" "$mode" >>"$report"
  fi
}

while read -r name pdk rel; do
  [[ -z "$name" || "$name" == \#* ]] && continue
  [[ -n "$filter" && ! "$name" =~ $filter ]] && continue
  file="$src/$rel"
  if [[ ! -f "$file" ]]; then
    printf '%-44s %-5s FAIL missing input %s\n' "$name" all "$rel" >>"$report"
    continue
  fi
  run_mode "$name" "$pdk" "$file" spice
  run_mode "$name" "$pdk" "$file" lvs
done <"$here/benches.txt"
rm -rf "$work"

echo "goldens in $out"
for p in xs sky130 gf180 ihp; do
  ok_s=$(grep -c "^$p-[^ ]* *spice *ok" "$report" || true)
  ok_l=$(grep -c "^$p-[^ ]* *lvs *ok" "$report" || true)
  bad=$(grep -c "^$p-.* FAIL" "$report" || true)
  printf '  %-7s spice ok %4d   lvs ok %4d   failures %4d\n' "$p" "$ok_s" "$ok_l" "$bad"
done
if grep -q ' FAIL ' "$report"; then
  echo "failures (see $report):"
  grep ' FAIL ' "$report"
  exit 1
fi
